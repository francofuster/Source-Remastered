"""Launcher icons of the APK from tools/zeq2icon.png (square, 1080 px).

Android 8+ gets an adaptive icon: the picture fills its background layer
(108 dp, the launcher shows the middle 72 dp in its own shape) and the
foreground is empty. Older versions get the square picture.

    python Android/tools/make_icon.py
"""
import os
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, 'zeq2icon.png')
RES = os.path.join(HERE, '..', 'app', 'src', 'main', 'res')

DENSITIES = {'mdpi': 1.0, 'hdpi': 1.5, 'xhdpi': 2.0, 'xxhdpi': 3.0, 'xxxhdpi': 4.0}


def main():
    icon = Image.open(SRC).convert('RGB')
    for name, scale in DENSITIES.items():
        folder = os.path.join(RES, 'mipmap-' + name)
        os.makedirs(folder, exist_ok=True)
        icon.resize((round(48 * scale),) * 2, Image.LANCZOS).save(os.path.join(folder, 'ic_launcher.png'), optimize=True)
        icon.resize((round(108 * scale),) * 2, Image.LANCZOS).save(os.path.join(folder, 'ic_launcher_background.png'), optimize=True)

    folder = os.path.join(RES, 'mipmap-anydpi-v26')
    os.makedirs(folder, exist_ok=True)
    with open(os.path.join(folder, 'ic_launcher.xml'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('<?xml version="1.0" encoding="utf-8"?>\n'
                '<!-- Generated by Android/tools/make_icon.py -->\n'
                '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
                '    <background android:drawable="@mipmap/ic_launcher_background" />\n'
                '    <foreground android:drawable="@android:color/transparent" />\n'
                '</adaptive-icon>\n')
    print('icons written to', os.path.normpath(RES))


if __name__ == '__main__':
    main()
